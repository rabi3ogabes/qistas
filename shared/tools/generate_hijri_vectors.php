<?php

/*
 * Generates the Umm al-Qura calendar that the website, the PDFs and the app all read (Sprint 2 Task 2, Win Plan CT26),
 * from ICU's `islamic-umalqura` calendar (PHP intl), so every side agrees to the day whatever ICU a server runs:
 *
 *   shared/hijri-vectors.json              the month lengths, and sample dates (month ends, year boundaries) with the
 *                                          Hijri day and its wording in every language; PHP and Dart must reproduce them
 *   web/app/Support/HijriTable.php         the month lengths for PHP
 *   app/lib/core/l10n/hijri_table.dart     the same for Dart
 *
 * Run from the repository root:  php shared/tools/generate_hijri_vectors.php
 * The month names here are the reference: web/lang/app/*.json and app/lib/core/l10n/hijri.dart must say the same.
 */

const FIRST_YEAR = 1356;
const LAST_YEAR = 1500;

$names = [
    'en' => ['Muharram', 'Safar', 'Rabi al-Awwal', 'Rabi al-Akhir', 'Jumada al-Ula', 'Jumada al-Akhirah', 'Rajab', 'Shaban', 'Ramadan', 'Shawwal', 'Dhu al-Qadah', 'Dhu al-Hijjah'],
    'ar' => ['محرم', 'صفر', 'ربيع الأول', 'ربيع الآخر', 'جمادى الأولى', 'جمادى الآخرة', 'رجب', 'شعبان', 'رمضان', 'شوال', 'ذو القعدة', 'ذو الحجة'],
    'fr' => ['Mouharram', 'Safar', 'Rabia al-Awal', 'Rabia al-Thani', 'Joumada al-Oula', 'Joumada al-Thania', 'Rajab', 'Chaabane', 'Ramadan', 'Chawwal', 'Dhou al-Qi’da', 'Dhou al-Hijja'],
    'es' => ['Muharram', 'Safar', 'Rabi al-Awal', 'Rabi al-Thani', 'Yumada al-Ula', 'Yumada al-Thani', 'Rayab', 'Shaabán', 'Ramadán', 'Shawwal', 'Dhu al-Qada', 'Dhu al-Hiyya'],
    'ur' => ['محرم', 'صفر', 'ربیع الاول', 'ربیع الثانی', 'جمادی الاول', 'جمادی الثانی', 'رجب', 'شعبان', 'رمضان', 'شوال', 'ذوالقعدہ', 'ذوالحجہ'],
];
$patterns = ['en' => ':day :month :year AH', 'ar' => ':day :month :year هـ', 'fr' => ':day :month :year H', 'es' => ':day :month :year H', 'ur' => ':day :month :year ھ'];

$utc = new DateTimeZone('UTC');
$calendar = IntlCalendar::createInstance($utc, 'en@calendar=islamic-umalqura');

/** The Gregorian day a Hijri month starts on, and how long it is. */
$month = function (int $year, int $month) use ($calendar, $utc): array {
    $calendar->clear();
    $calendar->setDateTime($year, $month - 1, 1, 12, 0, 0);
    $start = (new DateTimeImmutable('@'.intdiv((int) $calendar->getTime(), 1000)))->setTimezone($utc)->format('Y-m-d');

    return [$start, $calendar->getActualMaximum(IntlCalendar::FIELD_DAY_OF_MONTH)];
};

$years = [];
$epoch = null;
$expected = null;
for ($y = FIRST_YEAR; $y <= LAST_YEAR; $y++) {
    $bits = '';
    for ($m = 1; $m <= 12; $m++) {
        [$start, $length] = $month($y, $m);
        if (! in_array($length, [29, 30], true)) {
            throw new RuntimeException("{$y}-{$m} has {$length} days.");
        }
        $epoch ??= $start;
        if ($expected !== null && $start !== $expected) {
            throw new RuntimeException("{$y}-{$m} starts on {$start}, expected {$expected}.");
        }
        $expected = (new DateTimeImmutable($start, $utc))->modify("+{$length} days")->format('Y-m-d');
        $bits .= $length === 30 ? '1' : '0';
    }
    $years[(string) $y] = $bits;
}

$hijriOf = function (string $gregorian) use ($utc): array {
    $formatter = new IntlDateFormatter('en@calendar=islamic-umalqura', IntlDateFormatter::NONE, IntlDateFormatter::NONE, $utc, IntlDateFormatter::TRADITIONAL, 'y-M-d');

    return array_map('intval', explode('-', $formatter->format(new DateTimeImmutable($gregorian.' 12:00:00', $utc))));
};

// Samples: every month's first and last day around today, both ends of the table, leap days and a few plain days.
$dates = ['1937-03-14', '2077-11-16', '2024-02-29', '2028-02-29', '2026-02-01', '2026-10-11', '1999-12-31', '2000-01-01'];
for ($y = 1446; $y <= 1449; $y++) {
    for ($m = 1; $m <= 12; $m++) {
        [$start, $length] = $month($y, $m);
        $dates[] = $start;
        $dates[] = (new DateTimeImmutable($start, $utc))->modify('+'.($length - 1).' days')->format('Y-m-d');
    }
}
$dates = array_values(array_unique($dates));
sort($dates);

$samples = [];
foreach ($dates as $gregorian) {
    [$hy, $hm, $hd] = $hijriOf($gregorian);
    $words = [];
    foreach ($patterns as $language => $pattern) {
        $words[$language] = strtr($pattern, [':day' => (string) $hd, ':month' => $names[$language][$hm - 1], ':year' => (string) $hy]);
    }
    $samples[] = ['gregorian' => $gregorian, 'hijri' => [$hy, $hm, $hd], 'words' => $words];
}

$root = dirname(__DIR__, 2);
$json = [
    '_note' => 'GENERATED by shared/tools/generate_hijri_vectors.php from ICU '.INTL_ICU_VERSION.' (islamic-umalqura). Do not edit by hand.',
    'calendar' => 'islamic-umalqura',
    'first_year' => FIRST_YEAR,
    'last_year' => LAST_YEAR,
    'epoch' => $epoch,
    'months' => $years,
    'names' => $names,
    'patterns' => $patterns,
    'samples' => $samples,
];
file_put_contents($root.'/shared/hijri-vectors.json', json_encode($json, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES)."\n");

$rows = array_chunk(array_values($years), 6);
$php = "<?php\n\nnamespace App\\Support;\n\n/**\n * The Umm al-Qura calendar from ".FIRST_YEAR.' to '.LAST_YEAR." AH, GENERATED by shared/tools/generate_hijri_vectors.php from ICU\n"
    ." * (do not edit by hand). Each year is twelve month lengths, Muharram first: 1 is a 30-day month, 0 a 29-day one.\n */\nfinal class HijriTable\n{\n"
    ."    public const FIRST_YEAR = ".FIRST_YEAR.";\n\n    public const LAST_YEAR = ".LAST_YEAR.";\n\n    /** The Gregorian day of 1 Muharram FIRST_YEAR. */\n"
    ."    public const EPOCH = '{$epoch}';\n\n    public const YEARS = [\n";
foreach ($rows as $row) {
    $php .= "        '".implode("', '", $row)."',\n";
}
$php .= "    ];\n}\n";
file_put_contents($root.'/web/app/Support/HijriTable.php', $php);

$dart = "// GENERATED by shared/tools/generate_hijri_vectors.php from ICU (islamic-umalqura). Do not edit by hand.\n\n"
    ."/// The first and last Hijri years the table covers.\nconst hijriFirstYear = ".FIRST_YEAR.";\nconst hijriLastYear = ".LAST_YEAR.";\n\n"
    ."/// The Gregorian day of 1 Muharram [hijriFirstYear].\nconst hijriEpoch = '{$epoch}';\n\n"
    ."/// Each year is twelve month lengths, Muharram first: 1 is a 30-day month, 0 a 29-day one.\nconst hijriYears = <String>[\n";
foreach ($rows as $row) {
    $dart .= "  '".implode("', '", $row)."',\n";
}
$dart .= "];\n";
file_put_contents($root.'/app/lib/core/l10n/hijri_table.dart', $dart);

echo count($years).' years, '.count($samples)." samples, epoch {$epoch}\n";
