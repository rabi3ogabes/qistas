#!/usr/bin/env node
/*
 * Writes shared/theme-vectors.json: what the reference theme engine (brand/shared/qistas-theme.js) answers for a set of
 * brand-colour choices. The PHP engine (web/app/Theme/ThemeEngine.php) must give the same palette token for token; its
 * tests read this file, the way the schedule maths reads shared/schedule-vectors.json.
 *
 *     node brand/tools/make-theme-vectors.cjs
 */
const fs = require('node:fs');
const path = require('node:path');
const Q = require(path.join(__dirname, '..', 'shared', 'qistas-theme.js'));
const seed = require(path.join(__dirname, '..', 'tokens', 'themes.seed.json'));

const base = seed.themes.find((t) => t.kind === 'base');

/** The base theme plus one theme that pins [pins]; resolved like any published look. */
function resolveWith(pins, safeguard) {
  const themes = [
    base,
    { id: 'x', kind: 'event', name: { en: 'x' }, status: 'published', priority: 1, scope: { countries: ['*'], plans: ['*'], tenants: ['*'] }, schedule: { always: true }, tokens: { light: pins.light || {}, dark: pins.dark || {} } },
  ];

  return Q.resolve({ themes, safeguard, now: new Date('2026-10-09T12:00:00Z') });
}

const cases = [
  ['the factory look', {}],
  ['a green primary', { light: { primary: '#0F5132' } }],
  ['a deep indigo primary', { light: { primary: '#1B1B3A' } }],
  ['a pale primary', { light: { primary: '#7FD1B9' } }],
  ['a sienna accent', { light: { accent: '#A0522D' } }],
  ['a pale accent', { light: { accent: '#F2D98A' } }],
  ['a purple interactive colour', { light: { info: '#6A1B9A' } }],
  ['emerald: primary, accent and interactive together', { light: { primary: '#0B4F3C', accent: '#D8B04A', info: '#1F7A8C' } }],
  ['a white canvas', { light: { bg: '#FFFFFF' } }],
  ['a hostile palette: black on black', { light: { primary: '#000000', onPrimary: '#000000', bg: '#111111', ink: '#161616' } }],
  ['a pale paid colour', { light: { positive: '#3FBF8F' } }],
  ['a pinned dark canvas', { dark: { bg: '#000000' } }],
  ['a saturated red primary', { light: { primary: '#B3261E' } }],
  ['a grey primary', { light: { primary: '#444444' } }],
  ['a green primary with a pinned dark canvas and card', { light: { primary: '#0F5132' }, dark: { bg: '#000000', surface: '#0A0A0A' } }],
  ['a sienna accent with its own dark accent', { light: { accent: '#A0522D' }, dark: { accent: '#E6B07A' } }],
  ['a purple interactive colour with its own dark one', { light: { info: '#6A1B9A' }, dark: { info: '#C9A0E8' } }],
  ['a pinned button colour and its text', { light: { primary: '#0B4F3C', action: '#7A1F2B', onAction: '#FFFFFF' } }],
];

const out = {
  _note: 'Generated by brand/tools/make-theme-vectors.cjs from brand/shared/qistas-theme.js. Do not edit by hand.',
  base: { light: base.tokens.light, dark: base.tokens.dark },
  cases: cases.map(([name, pins]) => {
    const repaired = resolveWith(pins, true);
    const raw = resolveWith(pins, false);
    const failing = Q.validate(raw.tokens).filter((c) => !c.pass).map((c) => `${c.mode}:${c.fg}/${c.bg}`);

    return { name, pins, resolved: repaired.tokens, unrepaired: raw.tokens, failingBeforeRepair: failing, repairedCount: repaired.repaired.length };
  }),
  colour: [
    ['contrast', '#000000', '#FFFFFF'], ['contrast', '#C9A25B', '#F7F3EA'], ['contrast', '#0B1F44', '#F7F3EA'],
  ].map(([fn, a, b]) => ({ fn, a, b, result: Q.contrast(a, b) })),
  readableOn: ['#0B1F44', '#C9A25B', '#7FD1B9', '#000000', '#FFFFFF', '#1C6BA4'].map((bg) => ({ bg, result: Q.readableOn(bg) })),
  ensureContrast: [['#C9A25B', '#F7F3EA', 4.5], ['#F2D98A', '#FFFFFF', 4.6], ['#444444', '#333333', 4.5]].map(([fg, bg, min]) => ({ fg, bg, min, result: Q.ensureContrast(fg, bg, min) })),
  mix: [['#0B1F44', '#FFFFFF', 0.1], ['#C9A25B', '#000000', 0.35]].map(([a, b, t]) => ({ a, b, t, result: Q.mix(a, b, t) })),
  lighten: [['#0B1F44', 0.1], ['#C9A25B', -0.04]].map(([hex, amt]) => ({ hex, amt, result: Q.lighten(hex, amt) })),
};

const target = path.join(__dirname, '..', '..', 'shared', 'theme-vectors.json');
fs.writeFileSync(target, JSON.stringify(out, null, 2) + '\n');
console.log('wrote ' + path.relative(process.cwd(), target) + ' (' + out.cases.length + ' cases)');
