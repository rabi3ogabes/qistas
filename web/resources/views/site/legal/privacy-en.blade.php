<h1 class="display">Privacy Policy</h1>
<p class="updated">Last updated 7 October 2026</p>

<p>This policy explains what personal information Qistas collects, why, and the choices you have. Qistas is software that businesses use to manage instalment sales, so there are two groups of people whose information we handle: the business owners and team members who use Qistas, and the customers those businesses record in it.</p>

<h2>What we collect</h2>
<ul>
    <li><strong>Your account:</strong> your name, email address, preferred language and a password, which we store only in hashed form. If you turn on two-step sign-in we also store the secret needed to check your codes, encrypted.</li>
    <li><strong>Your business:</strong> the business name, country and currency you choose when you sign up.</li>
    <li><strong>The records you enter:</strong> customers (name, phone numbers, email, address, notes and an optional national ID, which we encrypt), contracts, instalment schedules and payments.</li>
    <li><strong>Security and service logs:</strong> sign-in events, the IP address and browser type of requests, and an audit log of sensitive actions such as plan changes, so we can keep accounts safe and investigate problems.</li>
    <li><strong>Billing:</strong> if you buy a paid plan, our payment provider handles your card details. We do not store card numbers.</li>
</ul>

<h2>Why we use it</h2>
<ul>
    <li>To provide Qistas to you and keep your records available and correct.</li>
    <li>To keep the service and your account secure, and to prevent abuse.</li>
    <li>To take payment for paid plans and to send you messages you need, such as email verification and password resets.</li>
    <li>To fix problems and improve the service.</li>
    <li>To meet our legal obligations.</li>
</ul>
<p>We do not sell personal information, and we do not use it for advertising.</p>

<h2>Your customers’ information</h2>
<p>When a business records its customers in Qistas, that business decides what to record and why. We process that information only on the business’s behalf, to provide the service. If you are a customer of a business that uses Qistas and want to see, correct or remove your information, please contact that business first.</p>

<h2>Who we share it with</h2>
<p>We use trusted providers to run Qistas: infrastructure and database hosting, email delivery and payment processing. They may handle personal information only to perform those services for us and under obligations to protect it. We may disclose information if the law requires it, or to protect people’s safety and the security of the service.</p>

<h2>How long we keep it</h2>
<p>We keep your information while your account is open. When you close your account we delete its data within a reasonable period, except records we must keep by law, and backups, which are overwritten on their normal cycle.</p>

<h2>How we protect it</h2>
<p>Each business’s data is separated from every other’s. Connections are encrypted, national IDs are encrypted at rest, passwords are hashed, sign-in attempts are limited, and sensitive actions are logged. No system is perfectly secure, but we take these measures seriously and review them as the service grows.</p>

<h2>Your rights</h2>
<p>Depending on where you live, you may have the right to access, correct, export or delete your personal information, to object to certain uses, and to complain to a data-protection authority. You can change most of your details in your account, and you can contact us to exercise any of these rights.</p>

<h2>Cookies</h2>
<p>We use only the cookies the service needs to work: one to keep you signed in, one to protect forms from forgery, and small ones that remember your language and your light or dark preference. We do not use advertising or cross-site tracking cookies.</p>

<h2>Children</h2>
<p>Qistas is for businesses and is not directed at anyone under 18.</p>

<h2>Changes to this policy</h2>
<p>If we change this policy in a significant way, we will tell you through the service or by email before the change takes effect.</p>

